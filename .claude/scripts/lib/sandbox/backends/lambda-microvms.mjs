export function runnerDockerfile(manifest) {
  return [
    `FROM ${imageRef(manifest.baseImages.microvm)}`,
    '# Amazon Linux 2023 locks its package repositories to the release of the pinned image, so this install is repeatable.',
    `RUN if command -v dnf >/dev/null 2>&1; then PM=dnf; else PM=microdnf; fi && $PM install -y python${RUNNER_PYTHON} tar gzip && $PM clean all`,
    'COPY runner.py /opt/maxwell/runner.py',
    `ENV MAXWELL_RUNNER_ROOT=${HOSTED_ROOT} MAXWELL_RUNNER_PORT=${RUNNER_PORT} PYTHONDONTWRITEBYTECODE=1`,
    'USER 65532:65532',
    `EXPOSE ${RUNNER_PORT}`,
    `CMD ["python${RUNNER_PYTHON}", "/opt/maxwell/runner.py"]`,
    '',
  ].join('\n');
}

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (buf) => {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};

// A deterministic zip (stored, fixed 1980-01-01 timestamps), so the same runner always has the same hash and image name.
export function storedZip(entries) {
  const parts = [];
  const central = [];
  let offset = 0;
  for (const [name, content] of entries) {
    const data = Buffer.from(content);
    const fname = Buffer.from(name);
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x21, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(fname.length, 26);
    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50, 0);
    entry.writeUInt16LE((3 << 8) | 20, 4);
    entry.writeUInt16LE(20, 6);
    entry.writeUInt16LE(0x21, 14);
    entry.writeUInt32LE(crc, 16);
    entry.writeUInt32LE(data.length, 20);
    entry.writeUInt32LE(data.length, 24);
    entry.writeUInt16LE(fname.length, 28);
    entry.writeUInt32LE((0o100644 << 16) >>> 0, 38);
    entry.writeUInt32LE(offset, 42);
    parts.push(local, fname, data);
    central.push(entry, fname);
    offset += local.length + fname.length + data.length;
  }
  const cd = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cd.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...parts, cd, end]);
}

export function runnerArtifact(manifest, memoryMiB) {
  const zip = storedZip([['Dockerfile', runnerDockerfile(manifest)], ['runner.py', RUNNER_PY]]);
  const sha256 = createHash('sha256').update(zip).digest('hex');
  return { zip, sha256, name: `maxwell-runner-${sha256.slice(0, 16)}-${memoryMiB}` };
}

const memorySize = (mb) => MEMORY_SIZES.find((m) => m >= mb) || MEMORY_SIZES[MEMORY_SIZES.length - 1];
const ingressConnector = (region) => `arn:aws:lambda:${region}:aws:network-connector:aws-network-connector:ALL_INGRESS`;
const defaultSleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const notFound = (err) => Boolean(err) && (err.name === 'ResourceNotFoundException' || (err.$metadata && err.$metadata.httpStatusCode === 404));

function checkConfig({ providerConfig = {}, region, network }) {
  if (!region) throw new ExecutorError('not-configured', 'lambda-microvms needs static.region (ap-south-1 is Mumbai); run /connect-sandbox');
  const missing = REQUIRED_SETTINGS.filter((k) => !providerConfig[k]);
  if (missing.length) throw new ExecutorError('not-configured', `providers.lambda-microvms needs ${missing.join(', ')}; run /connect-sandbox`);
  if (network && network !== 'none') throw new ExecutorError('invalid-config', 'lambda-microvms runs scanners only with static.network none: egress is whatever the VPC egress connector allows');
}

async function openClients(manifest, { region, providerConfig, deps }) {
  if (!manifest.baseImages || !manifest.baseImages.microvm) throw new ExecutorError('not-pinned', 'toolchain.json pins no baseImages.microvm for the Lambda MicroVMs runner');
  const load = deps.loadSdk || loadSdk;
  // One after the other: the first call installs the pinned lockfile, the second only verifies it.
  const mv = await load(manifest, 'lambda-microvms');
  const s3 = await load(manifest, 'lambda-microvms', { pkg: S3_SDK });
  const config = { region, ...(providerConfig.profile ? { profile: providerConfig.profile } : {}) };
  const client = new mv.LambdaMicrovmsClient(config);
  const s3client = new s3.S3Client(config);
  return { send: (command, input) => client.send(new mv[command](input)), s3send: (command, input) => s3client.send(new s3[command](input)) };
}

// The runner image for this toolchain and size, built on first use and reused afterwards (its name is its content hash).
export async function ensureRunnerImage(c, manifest, { region, providerConfig, memoryMiB, sleep = defaultSleep, waitSeconds = 1800 }) {
  const art = runnerArtifact(manifest, memoryMiB);
  const get = () => c.send('GetMicrovmImageCommand', { imageIdentifier: art.name });
  let image = await get().catch((err) => { if (notFound(err)) return null; throw err; });
  if (!image) {
    const key = `maxwell/microvm-runner/${art.name}.zip`;
    await c.s3send('PutObjectCommand', { Bucket: providerConfig.artifactBucket, Key: key, Body: art.zip, ContentType: 'application/zip', ChecksumSHA256: Buffer.from(art.sha256, 'hex').toString('base64') });
    image = await c.send('CreateMicrovmImageCommand', {
      name: art.name,
      description: `Maxwell scan runner ${art.sha256.slice(0, 16)}: pinned AL2023 container with Python ${RUNNER_PYTHON}, no scanners`,
      baseImageArn: `arn:aws:lambda:${region}:aws:microvm-image:al2023-1`,
      ...(providerConfig.baseImageVersion ? { baseImageVersion: providerConfig.baseImageVersion } : {}),
      buildRoleArn: providerConfig.buildRoleArn,
      codeArtifact: { uri: `s3://${providerConfig.artifactBucket}/${key}` },
      cpuConfigurations: [{ architecture: 'ARM_64' }],
      resources: [{ minimumMemoryInMiB: memoryMiB }],
      hooks: { port: RUNNER_PORT, microvmImageHooks: { ready: 'ENABLED', readyTimeoutInSeconds: 300 }, microvmHooks: { run: 'ENABLED', runTimeoutInSeconds: 60 } },
      logging: { disabled: {} },
      tags: { 'maxwell:runner-sha256': art.sha256 },
      clientToken: art.name,
    }).catch((err) => { if (err && err.name === 'ConflictException') return get(); throw err; });
  }
  for (let i = 0; !(['CREATED', 'UPDATED'].includes(image.state) && image.latestActiveImageVersion); i++) {
    if (!['CREATING', 'UPDATING', 'CREATED', 'UPDATED'].includes(image.state)) {
      throw new ExecutorError('image-build-failed', `the Maxwell runner image ${art.name} in ${region} is ${image.state}${image.latestFailedImageVersion ? ` (failed version ${image.latestFailedImageVersion})` : ''}; delete it to rebuild`);
    }
    if (i >= Math.ceil(waitSeconds / 10)) throw new ExecutorError('image-build-timeout', `the Maxwell runner image ${art.name} was still ${image.state} after ${waitSeconds}s`);
    await sleep(10000);
    image = await get();
  }
  const version = await c.send('GetMicrovmImageVersionCommand', { imageIdentifier: art.name, imageVersion: image.latestActiveImageVersion });
  return { name: art.name, imageArn: image.imageArn, imageVersion: image.latestActiveImageVersion, baseImageVersion: version.baseImageVersion, runnerSha256: art.sha256 };
}

function runnerApi(call, sleep) {
  const json = async (res, what) => {
    const body = await res.text();
    if (!res.ok) throw new ExecutorError('runner-failed', `${what} in the MicroVM failed with HTTP ${res.status}: ${clip(body, 300)}`);
    return JSON.parse(body);
  };
  return {
    upload: async (bytes) => json(await call('PUT', '/maxwell/v1/bundle', bytes, 'application/gzip'), 'uploading the bundle'),
    exec: async (argv, { cwd = HOSTED_ROOT, env = {}, seconds }) => {
      const { jobId } = await json(await call('POST', '/maxwell/v1/exec', JSON.stringify({ argv, cwd, env, timeoutSeconds: seconds })), 'starting a command');
      for (let i = 0; ; i++) {
        const job = await json(await call('GET', `/maxwell/v1/jobs/${jobId}`), 'polling a command');
        if (job.state === 'done') return job;
        if (i * 2 > seconds + 120) throw new ExecutorError('runner-timeout', `a command in the MicroVM did not finish within ${seconds}s`);
        await sleep(2000);
      }
    },
    result: async () => {
      const res = await call('GET', '/maxwell/v1/result');
      return res.ok ? Buffer.from(await res.arrayBuffer()) : null;
    },
  };
}

// Runs one MicroVM for fn and always terminates it.
async function withMicrovm(c, image, { region, providerConfig, seconds, deps }, fn) {
  const sleep = deps.sleep || defaultSleep;
  const http = deps.http || globalThis.fetch;
  const lifetime = Math.min(28800, seconds + 1800);
  let vm = await c.send('RunMicrovmCommand', {
    imageIdentifier: image.imageArn,
    imageVersion: image.imageVersion,
    ingressNetworkConnectors: [ingressConnector(region)],
    egressNetworkConnectors: [providerConfig.egressConnectorArn],
    idlePolicy: { autoResumeEnabled: false, maxIdleDurationSeconds: lifetime, suspendedDurationSeconds: 60 },
    maximumDurationInSeconds: lifetime,
    logging: { disabled: {} },
    clientToken: randomUUID(),
  });
  const id = vm.microvmId;
  try {
    for (let i = 0; vm.state !== 'RUNNING'; i++) {
      if (['TERMINATING', 'TERMINATED'].includes(vm.state)) throw new ExecutorError('microvm-failed', `MicroVM ${id} stopped before it ran: ${vm.stateReason || vm.state}`);
      if (i >= 150) throw new ExecutorError('microvm-timeout', `MicroVM ${id} did not reach RUNNING within 5 minutes`);
      await sleep(2000);
      vm = await c.send('GetMicrovmCommand', { microvmIdentifier: id });
    }
    const { authToken } = await c.send('CreateMicrovmAuthTokenCommand', { microvmIdentifier: id, expirationInMinutes: Math.ceil(lifetime / 60), allowedPorts: [{ port: RUNNER_PORT }] });
    const token = authToken && authToken['X-aws-proxy-auth'];
    if (!token) throw new ExecutorError('microvm-failed', `no auth token was issued for MicroVM ${id}`);
    const endpoint = String(vm.endpoint).replace(/\/+$/, '');
    const base = endpoint.startsWith('https://') ? endpoint : `https://${endpoint}`;
    const call = (method, path, body, contentType = 'application/json') => http(`${base}${path}`, {
      method,
      headers: { 'X-aws-proxy-auth': token, 'X-aws-proxy-port': String(RUNNER_PORT), ...(body !== undefined ? { 'Content-Type': contentType } : {}) },
      ...(body !== undefined ? { body } : {}),
    });
    return await fn(runnerApi(call, sleep));
  } finally {
    await c.send('TerminateMicrovmCommand', { microvmIdentifier: id }).catch(() => {});
  }
}

export async function runTool({ manifest, tool, argv, repoDir, resultPath, network, limits, region, providerConfig = {}, deps = {} }) {
  checkConfig({ providerConfig, region, network });
  const c = await openClients(manifest, { region, providerConfig, deps });
  const root = HOSTED_ROOT; const paths = sandboxPaths(root);
  const staged = await stageTool(manifest, tool, { oci: false, network: 'none', provider: 'lambda-microvms', root, platform: 'linux-arm64', sitePython: RUNNER_PYTHON, fetchImpl: deps.fetchImpl, run: deps.run });
  const staging = mkdtempSync(join(tmpdir(), 'maxwell-bundle-'));
  try {
    const bundle = packBundle(repoDir, join(staging, 'bundle.tgz'), { optDir: staged.optDir, run: deps.run });
    const image = await ensureRunnerImage(c, manifest, { region, providerConfig, memoryMiB: memorySize(limits.memoryMb), sleep: deps.sleep });
    return await withMicrovm(c, image, { region, providerConfig, seconds: limits.timeoutSeconds, deps }, async (runner) => {
      await runner.upload(readFileSync(bundle));
      for (const step of staged.prepare) {
        const r = await runner.exec(['sh', '-c', step], { cwd: root, seconds: 600, env: { PATH: PATH_ENV, ...(staged.prepareEnv || {}) } });
        if (r.exitCode !== 0) throw new ExecutorError('install-failed', `${tool.name} setup in the MicroVM failed: ${clip(r.stderr, 400)}`);
      }
      const env = { PATH: PATH_ENV, ...scannerEnv({ HOME: `${root}/home`, TMPDIR: `${root}/home` }), ...staged.env };
      const version = await runner.exec([...staged.invoke, ...tool.versionCheck.args], { cwd: root, seconds: 300, env });
      const versionOutput = `${version.stdout}${version.stderr}`.trim();
      if (!versionMatches(tool, versionOutput)) throw new ExecutorError('version-mismatch', `${tool.name} in the MicroVM printed "${versionOutput.split('\n')[0].slice(0, 160)}", expected ${tool.version}`);
      const r = await runner.exec([...staged.invoke, ...substitute(argv, paths)], { cwd: root, seconds: limits.timeoutSeconds, env });
      const bytes = await runner.result();
      if (bytes) writeFileSync(resultPath, bytes);
      return {
        exitCode: r.exitCode, timedOut: Boolean(r.timedOut), stdout: r.stdout || '', stderr: clip(r.stderr),
        provenance: { provider: 'lambda-microvms', isolation: 'microvm', network: 'none', region, toolVersion: tool.version, versionOutput: versionOutput.split('\n')[0], ...staged.pin, image: imageRef(manifest.baseImages.microvm), runnerImage: `${image.name}:${image.imageVersion}`, ...(image.baseImageVersion ? { baseImageVersion: image.baseImageVersion } : {}) },
      };
    });
  } finally {
    staged.cleanup();
    rmSync(staging, { recursive: true, force: true });
  }
}

// /connect-sandbox test: the MicroVM must run on ARM64 and must not open outbound connections through the connector.
export async function checkEgress({ manifest, providerConfig = {}, region, limits = { memoryMb: 4096 }, deps = {} }) {
  checkConfig({ providerConfig, region });
  const c = await openClients(manifest, { region, providerConfig, deps });
  const image = await ensureRunnerImage(c, manifest, { region, providerConfig, memoryMiB: memorySize(limits.memoryMb), sleep: deps.sleep });
  return withMicrovm(c, image, { region, providerConfig, seconds: 120, deps }, async (runner) => {
    const arch = await runner.exec(['uname', '-m'], { seconds: 60, env: { PATH: PATH_ENV } });
    const probe = await runner.exec([`python${RUNNER_PYTHON}`, '-c', EGRESS_PY], { seconds: 60, env: { PATH: PATH_ENV } });
    let reach = {};
    try { reach = JSON.parse(probe.stdout); } catch { /* reported below */ }
    if (reach.tcp !== false) {
      return { ok: false, detail: reach.tcp ? `the MicroVM reached 1.1.1.1:443, so ${providerConfig.egressConnectorArn} allows outbound traffic; remove the outbound rules from its security group` : `the egress probe in the MicroVM failed: ${clip(probe.stderr, 200)}` };
    }
    const dns = reach.dns ? '; names still resolve through the VPC resolver, so add a Route 53 Resolver DNS Firewall rule that blocks all domains for that VPC' : '';
    return { ok: arch.exitCode === 0, detail: `MicroVM (${String(arch.stdout).trim()}) in ${region} from ${image.name}:${image.imageVersion} could not open outbound connections${dns}` };
  });
}

