// lambda-microvms: AWS Lambda MicroVMs, one Firecracker MicroVM (ARM64) per scan in the customer's own AWS account and
// region (ap-south-1 is Mumbai). MicroVMs start from a Maxwell runner image that Lambda builds once per account, region
// and size: the digest-pinned AL2023 container (baseImages.microvm) with Python and the small HTTP runner below, and no
// scanner. The verified linux-arm64 binary or hash-locked arm64 wheels travel in the upload bundle, as with the other
// hosted providers. Ingress is only Lambda's token-authenticated endpoint; egress goes through the customer's VPC egress
// connector, whose security group must allow no outbound traffic. Image and MicroVM logging is disabled so nothing from
// a checkout reaches CloudWatch. Credentials: the AWS SDK default chain on this machine (providers.lambda-microvms.profile,
// SSO or an instance role); no key is stored. SDKs: @aws-sdk/client-lambda-microvms with @aws-sdk/client-s3, pinned in
// toolchain.json (API from the packages' type definitions; not yet exercised live).
import { createHash, randomUUID } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { imageRef, versionMatches } from '../../toolchain.mjs';
import { loadSdk } from '../sdk.mjs';
import { stageTool } from '../stage.mjs';
import { ExecutorError, HOSTED_ROOT, clip, packBundle, sandboxPaths, scannerEnv, substitute } from '../common.mjs';

export const CREDENTIALS = [];
const RUNNER_PORT = 8080;
const RUNNER_PYTHON = '3.12';
const S3_SDK = '@aws-sdk/client-s3';
const PATH_ENV = '/usr/local/bin:/usr/bin:/bin';
// Baseline sizes Lambda offers (1 vCPU per 2 GiB); a MicroVM bursts to four times its baseline.
const MEMORY_SIZES = [512, 1024, 2048, 4096, 8192];
const REQUIRED_SETTINGS = ['buildRoleArn', 'artifactBucket', 'egressConnectorArn'];

// The runner inside every MicroVM. One MicroVM serves one scan: Maxwell uploads the bundle, runs commands as argv with
// the environment it sends (never through a shell, never with the runner's own environment), reads the one result file
// and terminates the MicroVM. Lambda lifecycle hooks are acknowledged on the same port.
export const RUNNER_PY = String.raw`# Maxwell scan runner for AWS Lambda MicroVMs, generated by .claude/scripts/lib/sandbox/backends/lambda-microvms.mjs.
import json
import os
import subprocess
import tarfile
import threading
import uuid
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

ROOT = os.path.realpath(os.environ.get("MAXWELL_RUNNER_ROOT", "/tmp/maxwell"))
PORT = int(os.environ.get("MAXWELL_RUNNER_PORT", "8080"))
MAX_OUTPUT = 16 * 1024 * 1024
MAX_BUNDLE = 4 * 1024 * 1024 * 1024
JOBS = {}


def inside_root(path):
    real = os.path.realpath(path)
    return real == ROOT or real.startswith(ROOT + os.sep)


def text(data):
    return (data or b"")[-MAX_OUTPUT:].decode("utf-8", "replace")


def run_job(job, argv, cwd, env, timeout):
    try:
        done = subprocess.run(argv, cwd=cwd, env=env, stdin=subprocess.DEVNULL, capture_output=True, timeout=timeout)
        job.update(exitCode=done.returncode, stdout=text(done.stdout), stderr=text(done.stderr), timedOut=False)
    except subprocess.TimeoutExpired as err:
        job.update(exitCode=124, stdout=text(err.stdout), stderr=text(err.stderr), timedOut=True)
    except OSError as err:
        job.update(exitCode=127, stdout="", stderr=str(err), timedOut=False)
    job["state"] = "done"


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *args):
        pass

    def reply(self, status, body):
        data = body if isinstance(body, bytes) else json.dumps(body).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/octet-stream" if isinstance(body, bytes) else "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def read_body(self, limit):
        length = int(self.headers.get("Content-Length") or 0)
        if length > limit:
            raise ValueError("request body too large")
        return self.rfile.read(length) if length else b""

    def do_GET(self):
        if self.path == "/maxwell/v1/health":
            return self.reply(200, {"ok": True})
        if self.path.startswith("/maxwell/v1/jobs/"):
            job = JOBS.get(self.path.rsplit("/", 1)[-1])
            return self.reply(200, dict(job)) if job else self.reply(404, {"error": "no such job"})
        if self.path == "/maxwell/v1/result":
            path = os.path.join(ROOT, "out", "result")
            if not os.path.isfile(path) or os.path.islink(path) or not inside_root(path):
                return self.reply(404, {"error": "no result"})
            with open(path, "rb") as handle:
                return self.reply(200, handle.read())
        return self.reply(404, {"error": "not found"})

    def do_POST(self):
        if self.path.startswith("/aws/lambda-microvms/runtime/v1/"):
            self.read_body(1024 * 1024)
            return self.reply(200, {"ok": True})
        if self.path != "/maxwell/v1/exec":
            return self.reply(404, {"error": "not found"})
        try:
            request = json.loads(self.read_body(1024 * 1024) or b"{}")
            argv = request.get("argv")
            if not isinstance(argv, list) or not argv or not all(isinstance(a, str) for a in argv):
                raise ValueError("argv must be a non-empty list of strings")
            cwd = request.get("cwd") or ROOT
            if not inside_root(cwd):
                raise ValueError("cwd must be inside the runner root")
            env = {str(k): str(v) for k, v in (request.get("env") or {}).items()}
            timeout = max(1, min(int(request.get("timeoutSeconds") or 900), 28800))
        except (ValueError, TypeError, AttributeError) as err:
            return self.reply(400, {"error": str(err)})
        job_id = uuid.uuid4().hex
        JOBS[job_id] = {"state": "running"}
        threading.Thread(target=run_job, args=(JOBS[job_id], argv, cwd, env, timeout), daemon=True).start()
        return self.reply(202, {"jobId": job_id})

    def do_PUT(self):
        if self.path != "/maxwell/v1/bundle":
            return self.reply(404, {"error": "not found"})
        length = int(self.headers.get("Content-Length") or 0)
        if length <= 0 or length > MAX_BUNDLE:
            return self.reply(400, {"error": "the bundle must be a non-empty gzip tar under 4 GiB"})
        os.makedirs(ROOT, exist_ok=True)
        archive = os.path.join(ROOT, "bundle.tgz")
        remaining = length
        with open(archive, "wb") as handle:
            while remaining > 0:
                chunk = self.rfile.read(min(1024 * 1024, remaining))
                if not chunk:
                    break
                handle.write(chunk)
                remaining -= len(chunk)
        try:
            if remaining:
                return self.reply(400, {"error": "the bundle upload was incomplete"})
            with tarfile.open(archive, "r:gz") as tar:
                tar.extractall(ROOT, filter="data")
        except (tarfile.TarError, OSError) as err:
            return self.reply(400, {"error": "the bundle could not be unpacked safely: " + str(err)})
        finally:
            os.remove(archive)
        for name in ("out", "home"):
            os.makedirs(os.path.join(ROOT, name), exist_ok=True)
        return self.reply(200, {"bytes": length})


if __name__ == "__main__":
    os.makedirs(ROOT, exist_ok=True)
    ThreadingHTTPServer(("0.0.0.0", PORT), Handler).serve_forever()
`;

