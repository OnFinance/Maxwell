#!/usr/bin/env node
// Generates the OpenCode-facing mirror in .agents/ from the canonical .claude/ tree, and rewrites the
// "agent" and "command" sections of opencode.json so OpenCode can use the same specialists and commands.
//   .agents/agents/<name>.md         <- .claude/agents/<name>.md   (OpenCode agent frontmatter + body)
//   .agents/agents/<name>.prompt.md  <- body only; referenced from opencode.json as {file:...}
//   .agents/commands/<name>.md       <- .claude/commands/<name>.md (OpenCode command frontmatter + body)
//   .agents/workflows/<name>.js      <- .claude/workflows/<name>.js (verbatim; run via run-workflow.mjs)
//   .agents/scripts, .agents/schemas -> symlinks to ../.claude/{scripts,schemas}
//   opencode.json agent.* / command.* <- regenerated; every other key in opencode.json is preserved.
// .agents/skills and .agents/hooks are authored by hand (OpenCode-specific) and left untouched.
// Empirically verified (OpenCode 1.18): agents/commands are NOT auto-discovered from .agents/, skills are.
// Usage: sync-agents-mirror.mjs [--check]   (--check exits 2 if the mirror is stale, writing nothing)
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, readlinkSync, symlinkSync, unlinkSync, rmSync } from 'node:fs';
import matter from 'gray-matter';

const MODEL_MAP = {
  fable: 'anthropic/claude-fable-5-1',
  opus: 'anthropic/claude-opus-5',
  sonnet: 'anthropic/claude-sonnet-5',
  haiku: 'anthropic/claude-haiku-4-5-20251001',
};
// The generated marker is a YAML comment on line 2 of the frontmatter block so the mirrored files still start
// with '---' on line 1 (validate-data.mjs and both harnesses require that) while staying visibly generated.
const HEADER = '# GENERATED by .claude/scripts/sync-agents-mirror.mjs from .claude/ — do not edit; run `npm run sync:agents`\n';
const stringify = (content, fm) => matter.stringify(content, fm).replace(/^---\n/, '---\n' + HEADER);

function toOpenCodeModel(model) {
  if (!model || model === 'inherit') return undefined;
  if (MODEL_MAP[model]) return MODEL_MAP[model];
  if (model.includes('/')) return model;
  return `anthropic/${model}`;
}

// Claude tool allow-list -> OpenCode permission map. Anything not listed in `tools` is denied.
const OC_TOOLS = ['read', 'edit', 'write', 'patch', 'bash', 'webfetch', 'glob', 'grep', 'list', 'skill', 'task', 'todowrite', 'todoread'];
const CLAUDE_TO_OC = { Read: ['read'], Edit: ['edit', 'patch'], MultiEdit: ['edit', 'patch'], Write: ['write'], Bash: ['bash'], WebFetch: ['webfetch'], WebSearch: ['webfetch'], Glob: ['glob', 'list'], Grep: ['grep'], Agent: ['task'], Skill: ['skill'], TodoWrite: ['todowrite', 'todoread'] };
// Claude Code accepts tools as a YAML list or a comma/space separated string; specifiers such as
// 'Bash(kubectl get *)' contain spaces, so a string is split only at parenthesis depth 0.
function toolTokens(tools) {
  if (Array.isArray(tools)) return tools.map(String);
  if (typeof tools !== 'string') return [];
  const out = [];
  let cur = '';
  let depth = 0;
  for (const ch of tools) {
    if (ch === '(') depth++;
    else if (ch === ')') depth--;
    if (depth === 0 && /[\s,]/.test(ch)) { if (cur) out.push(cur); cur = ''; } else cur += ch;
  }
  if (cur) out.push(cur);
  return out;
}
function toPermission(tools, disallowed) {
  const perm = {};
  const allowed = toolTokens(tools);
  if (allowed.length) {
    for (const t of OC_TOOLS) perm[t] = 'deny';
    for (const t of allowed) for (const oc of CLAUDE_TO_OC[t.split('(')[0]] || []) perm[oc] = 'allow';
  }
  for (const t of toolTokens(disallowed)) for (const oc of CLAUDE_TO_OC[t.split('(')[0]] || []) perm[oc] = 'deny';
  return Object.keys(perm).length ? perm : undefined;
}

const body = (content) => content.replace(/^\n+/, '').replace(/\n+$/, '') + '\n';

export function convertAgent(src) {
  const { data, content } = matter(src);
  // mode all, not subagent: `opencode run --agent <name>` falls back to the default agent for a subagent-only agent
  // (OpenCode 1.18), which silently drops the agent's prompt and permissions.
  const fm = { description: data.description, mode: 'all' };
  const model = toOpenCodeModel(data.model);
  if (model) fm.model = model;
  const permission = toPermission(data.tools, data.disallowedTools);
  if (permission) fm.permission = permission;
  if (data['x-maxwell']) fm['x-maxwell'] = data['x-maxwell'];
  return { md: stringify(body(content), fm), prompt: body(content), config: { description: data.description, mode: 'all', ...(model ? { model } : {}), ...(permission ? { permission } : {}) } };
}

export function convertCommand(src) {
  const { data, content } = matter(src);
  const fm = { description: data.description };
  if (data.agent) fm.agent = data.agent;
  const model = toOpenCodeModel(data.model);
  if (model) fm.model = model;
  if (data['x-maxwell']) fm['x-maxwell'] = data['x-maxwell'];
  // OpenCode substitutes $ARGUMENTS and $1..$n exactly like Claude Code.
  return { md: stringify(body(content), fm), config: { description: data.description, template: body(content).trimEnd(), ...(data.agent ? { agent: data.agent } : {}), ...(model ? { model } : {}) } };
}

export function computeMirror() {
  const files = new Map();
  const agentConfig = {};
  const commandConfig = {};
  const list = (dir, ext) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(ext)).sort() : []);
  for (const f of list('.claude/agents', '.md')) {
    const name = f.replace(/\.md$/, '');
    const a = convertAgent(readFileSync(`.claude/agents/${f}`, 'utf8'));
    files.set(`.agents/agents/${name}.md`, a.md);
    files.set(`.agents/agents/${name}.prompt.md`, a.prompt);
    agentConfig[name] = { ...a.config, prompt: `{file:./.agents/agents/${name}.prompt.md}` };
  }
  for (const f of list('.claude/commands', '.md')) {
    const name = f.replace(/\.md$/, '');
    const c = convertCommand(readFileSync(`.claude/commands/${f}`, 'utf8'));
    files.set(`.agents/commands/${f}`, c.md);
    commandConfig[name] = c.config;
  }
  for (const f of list('.claude/workflows', '.js')) files.set(`.agents/workflows/${f}`, readFileSync(`.claude/workflows/${f}`, 'utf8'));
  const links = new Map([['.agents/scripts', '../.claude/scripts'], ['.agents/schemas', '../.claude/schemas']]);
  const current = existsSync('opencode.json') ? JSON.parse(readFileSync('opencode.json', 'utf8')) : { $schema: 'https://opencode.ai/config.json' };
  const opencode = { ...current, agent: agentConfig, command: commandConfig };
  files.set('opencode.json', JSON.stringify(opencode, null, 2) + '\n');
  return { files, links };
}

export function diffMirror() {
  const { files, links } = computeMirror();
  const stale = [];
  for (const [path, content] of files) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) stale.push(path);
  }
  for (const dir of ['.agents/agents', '.agents/commands', '.agents/workflows']) {
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir)) if (!files.has(`${dir}/${f}`) && f !== '.gitkeep') stale.push(`${dir}/${f} (orphan)`);
  }
  for (const [path, target] of links) {
    let current = null;
    try { current = readlinkSync(path); } catch { /* missing */ }
    if (current !== target) stale.push(`${path} -> ${target}`);
  }
  return stale;
}

export function writeMirror() {
  const { files, links } = computeMirror();
  for (const dir of ['.agents/agents', '.agents/commands', '.agents/workflows']) {
    mkdirSync(dir, { recursive: true });
    for (const f of readdirSync(dir)) if (!files.has(`${dir}/${f}`) && f !== '.gitkeep') rmSync(`${dir}/${f}`);
  }
  for (const [path, content] of files) writeFileSync(path, content);
  for (const [path, target] of links) {
    try { if (readlinkSync(path) === target) continue; unlinkSync(path); } catch { /* not a symlink */ }
    if (existsSync(path)) rmSync(path, { recursive: true });
    symlinkSync(target, path);
  }
  return files.size;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--check')) {
    const stale = diffMirror();
    if (stale.length) { console.error('mirror is stale:\n- ' + stale.join('\n- ')); process.exit(2); }
    console.log('mirror OK');
  } else {
    console.log(`mirror written (${writeMirror()} files)`);
  }
}
