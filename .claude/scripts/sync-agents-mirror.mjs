#!/usr/bin/env node
// Generates the OpenCode-facing mirror in .agents/ from the canonical .claude/ tree.
//   .agents/agents/<name>.md    <- .claude/agents/<name>.md   (frontmatter converted to OpenCode agent format)
//   .agents/commands/<name>.md  <- .claude/commands/<name>.md (frontmatter converted to OpenCode command format)
//   .agents/workflows/<name>.js <- .claude/workflows/<name>.js (verbatim; run via .agents/scripts/run-workflow.mjs)
//   .agents/scripts, .agents/schemas -> symlinks to ../.claude/{scripts,schemas}
// .agents/skills and .agents/hooks are authored by hand (OpenCode-specific) and left untouched.
// Usage: sync-agents-mirror.mjs [--check]   (--check exits 2 if the mirror is stale, writing nothing)
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, readlinkSync, symlinkSync, unlinkSync, rmSync } from 'node:fs';
import matter from 'gray-matter';

const MODEL_MAP = {
  fable: 'anthropic/claude-fable-5-1',
  opus: 'anthropic/claude-opus-5',
  sonnet: 'anthropic/claude-sonnet-5',
  haiku: 'anthropic/claude-haiku-4-5-20251001',
};
const HEADER = '<!-- GENERATED by .claude/scripts/sync-agents-mirror.mjs from .claude/ — do not edit; run `npm run sync:agents` -->\n';

function toOpenCodeModel(model) {
  if (!model || model === 'inherit') return undefined;
  if (MODEL_MAP[model]) return MODEL_MAP[model];
  if (model.includes('/')) return model;
  return `anthropic/${model}`;
}

// Claude tool allow-list -> OpenCode permission map. Anything not listed in `tools` is denied.
function toPermission(tools, disallowed) {
  const all = ['read', 'edit', 'bash', 'webfetch', 'glob', 'grep', 'list', 'write', 'patch', 'todowrite', 'todoread', 'skill', 'task'];
  const claudeToOc = { Read: ['read'], Edit: ['edit', 'patch'], Write: ['write'], MultiEdit: ['edit', 'patch'], Bash: ['bash'], WebFetch: ['webfetch'], WebSearch: ['webfetch'], Glob: ['glob', 'list'], Grep: ['grep'], Agent: ['task'], Skill: ['skill'], TodoWrite: ['todowrite', 'todoread'] };
  const perm = {};
  if (Array.isArray(tools) && tools.length) {
    for (const t of all) perm[t] = 'deny';
    for (const t of tools) for (const oc of claudeToOc[String(t).split('(')[0]] || []) perm[oc] = 'allow';
  }
  if (Array.isArray(disallowed)) for (const t of disallowed) for (const oc of claudeToOc[String(t).split('(')[0]] || []) perm[oc] = 'deny';
  return Object.keys(perm).length ? perm : undefined;
}

export function convertAgent(src) {
  const { data, content } = matter(src);
  const out = { description: data.description, mode: 'subagent' };
  const model = toOpenCodeModel(data.model);
  if (model) out.model = model;
  const permission = toPermission(data.tools, data.disallowedTools);
  if (permission) out.permission = permission;
  if (data['x-maxwell']) out['x-maxwell'] = data['x-maxwell'];
  return HEADER + matter.stringify(content.replace(/^\n+/, ''), out);
}

export function convertCommand(src, name) {
  const { data, content } = matter(src);
  const out = { description: data.description };
  if (data.agent) out.agent = data.agent;
  const model = toOpenCodeModel(data.model);
  if (model) out.model = model;
  if (data['x-maxwell']) out['x-maxwell'] = data['x-maxwell'];
  // OpenCode substitutes $ARGUMENTS and $1..$n exactly like Claude Code.
  return HEADER + matter.stringify(content.replace(/^\n+/, ''), out);
}

export function computeMirror() {
  const files = new Map();
  const list = (dir, ext) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(ext)).sort() : []);
  for (const f of list('.claude/agents', '.md')) files.set(`.agents/agents/${f}`, convertAgent(readFileSync(`.claude/agents/${f}`, 'utf8')));
  for (const f of list('.claude/commands', '.md')) files.set(`.agents/commands/${f}`, convertCommand(readFileSync(`.claude/commands/${f}`, 'utf8'), f.replace(/\.md$/, '')));
  for (const f of list('.claude/workflows', '.js')) files.set(`.agents/workflows/${f}`, readFileSync(`.claude/workflows/${f}`, 'utf8'));
  const links = new Map([['.agents/scripts', '../.claude/scripts'], ['.agents/schemas', '../.claude/schemas']]);
  return { files, links };
}

export function diffMirror() {
  const { files, links } = computeMirror();
  const stale = [];
  for (const [path, content] of files) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) stale.push(path);
  }
  for (const dir of ['.agents/agents', '.agents/commands', '.agents/workflows']) {
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir)) if (!files.has(`${dir}/${f}`) && f !== '.gitkeep') stale.push(`${dir}/${f} (orphan)`);
  }
  for (const [path, target] of links) {
    let current = null;
    try { current = readlinkSync(path); } catch { /* missing */ }
    if (current !== target) stale.push(`${path} -> ${target}`);
  }
  return stale;
}

export function writeMirror() {
  const { files, links } = computeMirror();
  for (const dir of ['.agents/agents', '.agents/commands', '.agents/workflows']) {
    mkdirSync(dir, { recursive: true });
    for (const f of readdirSync(dir)) if (!files.has(`${dir}/${f}`) && f !== '.gitkeep') rmSync(`${dir}/${f}`);
  }
  for (const [path, content] of files) writeFileSync(path, content);
  for (const [path, target] of links) {
    try { if (readlinkSync(path) === target) continue; unlinkSync(path); } catch { /* not a symlink */ }
    if (existsSync(path)) rmSync(path, { recursive: true });
    symlinkSync(target, path);
  }
  return files.size;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--check')) {
    const stale = diffMirror();
    if (stale.length) { console.error('mirror is stale:\n- ' + stale.join('\n- ')); process.exit(2); }
    console.log('mirror OK');
  } else {
    console.log(`mirror written (${writeMirror()} files)`);
  }
}
